#!/bin/bash

# ==============================================================================
# 🚀 الباش النهائي الحاسم (الإصدار V21) - تطبيق Mirror Scorpion
# 🛠️ الهدف: تصحيح الخطأ البرمجي الأخير في Kotlin وضمان البناء الأخضر
# 📤 رفع نهائي شامل لضمان النجاح التام
# ==============================================================================

set -e

echo "🚀 بدء عملية الحسم النهائي (الإصدار V21)..."

# دالة للرفع التلقائي
push_changes() {
    local phase_msg=$1
    echo "📤 رفع التعديلات النهائية: $phase_msg..."
    git add .
    git commit -m "$phase_msg" || echo "⚠️ لا توجد تغييرات."
    git push origin main
}

# ------------------------------------------------------------------------------
# المرحلة الأولى: التصحيح الجذري لملف BubbleOverlayService.kt
# ------------------------------------------------------------------------------
echo "📍 المرحلة 1: تصحيح أخطاء Kotlin البرمجية..."

# البحث عن ملف BubbleOverlayService.kt وتصحيح السطر 96
KOTLIN_FILE=$(find android -name "BubbleOverlayService.kt")

if [ -f "$KOTLIN_FILE" ]; then
    echo "📝 معالجة ملف: $KOTLIN_FILE"
    # استبدال المتغيرات المحجوزة _ بأسماء مقبولة برمجياً
    sed -i 's/{ _, /{ unused, /g' "$KOTLIN_FILE"
    sed -i 's/, _ ->/, unused ->/g' "$KOTLIN_FILE"
    # تصحيح إضافي لأي تكرار للشرطة السفلية المحجوزة
    sed -i 's/(_: / (unused: /g' "$KOTLIN_FILE"
    echo "✅ تم تصحيح الخطأ البرمجي بنجاح."
else
    echo "⚠️ لم يتم العثور على الملف، يرجى التأكد من المسار."
fi

push_changes "fix(final): resolve Kotlin reserved name error in BubbleOverlayService"

# ------------------------------------------------------------------------------
# المرحلة الثانية: تنظيف شامل وإعادة بناء الكاش
# ------------------------------------------------------------------------------
echo "📍 المرحلة 2: التنظيف النهائي..."

# حذف ملفات القفل والكاش لضمان بناء نظيف تماماً في GitHub
rm -rf .dart_tool
rm -f pubspec.lock
rm -rf build/

push_changes "chore(final): clean environment for the green build #765"

echo "----------------------------------------------------"
echo "✅ تم تنفيذ الباش الحاسم V21 بنجاح!"
echo "🚀 اذهب الآن إلى GitHub Actions.. هذا هو بناء النجاح الأخضر بإذن الله!"
echo "----------------------------------------------------"
